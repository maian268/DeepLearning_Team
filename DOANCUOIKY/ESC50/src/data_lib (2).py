import os
import torch
import torchaudio
from pathlib import Path
from typing import Union
import gdown

TARGET_SR = 22050
TARGET_LEN = 110250  # 5 giây × 22050 Hz
N_FFT = 1024
WIN_LENGTH = 1024
HOP_LENGTH = 512
F_MIN = 0
F_MAX = TARGET_SR // 2  # 11025 Hz

def wav_to_logmel(
    path: Union[str, Path],
    n_mels: int,
    device: str = "cpu"
) -> torch.Tensor:
    """
    Đọc file WAV và chuyển thành Log-Mel Spectrogram.

    Tham số:
        path: Đường dẫn file .wav
        n_mels: Số băng tần Mel (64 hoặc 128)
        device: Thiết bị tính toán ('cpu' hoặc 'cuda')

    Trả về:
        Log-Mel Spectrogram: tensor shape [1, n_mels, 216] (dtype: float32)
    """
      # 1. Đọc file âm thanh
    waveform, sr = torchaudio.load(path)
    waveform = waveform.to(device)

    # 2. Chuyển sang mono (nếu là stereo)
    if waveform.shape[0] > 1:
        waveform = torch.mean(waveform, dim=0, keepdim=True)

    # 3. Resample nếu tần số lấy mẫu khác TARGET_SR (22050)
    if sr != TARGET_SR:
        resampler = torchaudio.transforms.Resample(orig_freq=sr, new_freq=TARGET_SR).to(device)
        waveform = resampler(waveform)
    # 4. Chuẩn hóa độ dài (cắt hoặc đệm padding về đúng TARGET_LEN = 110250)
    num_samples = waveform.shape[1]
    if num_samples > TARGET_LEN:
        waveform = waveform[:, :TARGET_LEN]
    elif num_samples < TARGET_LEN:
        pad_len = TARGET_LEN - num_samples
        waveform = torch.nn.functional.pad(waveform, (0, pad_len))

    # 5. Khởi tạo bộ biến đổi MelSpectrogram
    mel_transform = torchaudio.transforms.MelSpectrogram(
        sample_rate=TARGET_SR,
        n_fft=N_FFT,
        win_length=WIN_LENGTH,
        hop_length=HOP_LENGTH,
        f_min=F_MIN,
        f_max=F_MAX,
        n_mels=n_mels
    ).to(device)

    # Tính Mel Spectrogram
    mel_spec = mel_transform(waveform)

    # 6. Chuyển sang thang đo Log-amplitude (dB) để có Log-Mel Spectrogram
    # Sử dụng hằng số nhỏ 1e-5 tránh lỗi log(0)
    log_mel_spec = torch.log(mel_spec + 1e-5)

    # Đảm bảo output có kích thước chính xác là [1, n_mels, 216]
    if log_mel_spec.shape[2] > 216:
        log_mel_spec = log_mel_spec[:, :, :216]
    elif log_mel_spec.shape[2] < 216:
        pad_time = 216 - log_mel_spec.shape[2]
        log_mel_spec = torch.nn.functional.pad(log_mel_spec, (0, pad_time))

    return log_mel_spec.float()

