# Import thư viện
import torch
import numpy as np
from typing import Tuple, Dict

# Hằng số cố định
NUM_FOLDS = 5
TRAIN_SIZE = 1200   # 3 fold × 400
VAL_SIZE = 400      # 1 fold × 400
TEST_SIZE = 400     # 1 fold × 400

# get_splits
def get_splits(
    cache: Dict,
    test_fold: int
) -> Tuple[Dict, Dict, Dict]:
    """
    Chia cache thành tập train/val/test theo quy tắc 5-fold.

    Quy tắc:
      - test_fold = fold dùng để kiểm tra
      - val_fold = (test_fold mod 5) + 1 → fold kế tiếp dùng làm validation
      - 3 fold còn lại = tập huấn luyện

    Tham số:
        cache: dict có khóa 'X', 'y', 'fold' (từ file logmel*.pt)
        test_fold: số fold dùng làm test (1→5)

    Trả về:
        train, val, test: mỗi phần là dict {X, y, indices}
    """
    all_folds = set(range(1, NUM_FOLDS + 1))

    # Xác định số fold cho từng tập
    val_fold = (test_fold % NUM_FOLDS) + 1
    train_folds = sorted(all_folds - {test_fold, val_fold})

    # Lấy chỉ số theo từng fold
    train_mask = torch.isin(cache['fold'], torch.tensor(list(train_folds)))
    val_mask = (cache['fold'] == val_fold)
    test_mask = (cache['fold'] == test_fold)

    # Kiểm tra không giao nhau
    assert not torch.any(train_mask & val_mask), "Train và Val có giao nhau!"
    assert not torch.any(train_mask & test_mask), "Train và Test có giao nhau!"
    assert not torch.any(val_mask & test_mask), "Val và Test có giao nhau!"

    # Tạo tập dữ liệu
    train = {
        'X': cache['X'][train_mask],
        'y': cache['y'][train_mask],
        'indices': torch.where(train_mask)[0]
    }
    val = {
        'X': cache['X'][val_mask],
        'y': cache['y'][val_mask],
        'indices': torch.where(val_mask)[0]
    }
    test = {
        'X': cache['X'][test_mask],
        'y': cache['y'][test_mask],
        'indices': torch.where(test_mask)[0]
    }

    # Kiểm tra kích thước
    assert len(train['X']) == TRAIN_SIZE, f"Train size sai: {len(train['X'])} ≠ {TRAIN_SIZE}"
    assert len(val['X']) == VAL_SIZE, f"Val size sai: {len(val['X'])} ≠ {VAL_SIZE}"
    assert len(test['X']) == TEST_SIZE, f"Test size sai: {len(test['X'])} ≠ {TEST_SIZE}"

    print(f"✅ Chia dữ liệu xong — Test fold={test_fold}, Val fold={val_fold}, Train folds={train_folds}")
    print(f"   Train: {len(train['X'])} | Val: {len(val['X'])} | Test: {len(test['X'])}")

    return train, val, test

# specaug_batch — Tăng cường dữ liệu trên batch
def specaug_batch(
    x: torch.Tensor,
    n_mels: int,
    max_mask_f_ratio: float = 0.125,  # ≤ n_mels/8
    max_mask_t: int = 24,
    num_masks_f: int = 2,
    num_masks_t: int = 2,
    training: bool = True
) -> torch.Tensor:
    """
    Áp dụng SpecAugment trên batch Log-Mel spectrogram.
    Chỉ thay đổi khi training=True.

    Tham số:
        x: Tensor shape [B, 1, n_mels, T=216]
        n_mels: số băng tần Mel (64 hoặc 128)
        max_mask_f_ratio: độ rộng tối đa mặt nạ tần số
        max_mask_t: độ rộng tối đa mặt nạ thời gian
        num_masks_f: số mặt nạ theo tần số
        num_masks_t: số mặt nạ theo thời gian
        training: tắt augment khi không huấn luyện

    Trả về:
        Tensor cùng shape với đầu vào
    """
    if not training:
        return x

    B, C, F, T = x.shape
    assert F == n_mels, f"n_mels không khớp: {F} ≠ {n_mels}"

    x_aug = x.clone()
    max_mask_f = max(int(n_mels * max_mask_f_ratio), 1)

    # Mặt nạ theo TẦN SỐ (trục Mel bin)
    for _ in range(num_masks_f):
        mask_width = torch.randint(0, max_mask_f + 1, (1,)).item()
        if mask_width > 0:
            f_start = torch.randint(0, F - mask_width + 1, (B,))
            for b in range(B):
                x_aug[b, :, f_start[b]:f_start[b]+mask_width, :] = 0.0

    # Mặt nạ theo THỜI GIAN
    for _ in range(num_masks_t):
        mask_width = torch.randint(0, max_mask_t + 1, (1,)).item()
        if mask_width > 0:
            t_start = torch.randint(0, T - mask_width + 1, (B,))
            for b in range(B):
                x_aug[b, :, :, t_start[b]:t_start[b]+mask_width] = 0.0

    return x_aug